import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await (await b.new_context(viewport={'width':1440,'height':860})).new_page()
        await pg.goto('file://'+__import__('os').path.dirname(__import__('os').path.dirname(__import__('os').path.abspath(__file__)))+'/pholver.html'); await pg.wait_for_timeout(700)
        await pg.click('#newTabCkt'); await pg.wait_for_timeout(500)
        await pg.evaluate("(()=>{const d=window.__pholver.cur;d.mode==='design'||window.__pholver.setMode('design');d.ck=CKT.createScene();d.view=null;window.__pholver.renderWorkspace()})()")
        await pg.wait_for_timeout(300)
        box=await pg.locator('#cv').bounding_box()
        v=await pg.evaluate('(()=>{const v=window.__pholver.cur.view;return [v.ox,v.oy,v.s]})()')
        W=lambda x,y:(box['x']+v[0]+x*v[2], box['y']+v[1]-y*v[2])
        async def click(x,y): await pg.mouse.click(*W(x,y)); await pg.wait_for_timeout(60)
        await pg.click('#ckAdd'); await pg.click('#cktTray [data-t=vsrc]'); await click(2,0)
        await pg.click('#ckAdd'); await pg.click('#cktTray [data-t=res]'); await pg.keyboard.press('r'); await click(0,1)
        print(await pg.evaluate('JSON.stringify(window.__pholver.cur.ck.items.map(i=>[i.type,i.x,i.y,i.rot]))'))
        await pg.click('#ckWire')
        for pt in [(0,4),(0,5),(5,5),(5,0)]: await click(*pt)
        await pg.keyboard.press('Escape')
        for pt in [(0,1),(0,0),(2,0),(5,0)]: await click(*pt)
        await pg.keyboard.press('Escape')
        print(await pg.evaluate('JSON.stringify(window.__pholver.cur.ck.items.map(i=>[i.type,i.x,i.y,i.rot,i.x1,i.y1,i.x2,i.y2]))'))
        await pg.evaluate("window.__pholver.setMode('simulate')"); await pg.wait_for_timeout(800)
        e=await pg.evaluate('window.__pholver.cur.ck.err'); n=await pg.evaluate('window.__pholver.cur.ck.items.filter(i=>i.type=="wire").length'); print(repr(e),n); assert e=='' and n==5, (e,n)
        await pg.screenshot(path='/tmp/e2e35.png'); await b.close()
asyncio.run(main())
